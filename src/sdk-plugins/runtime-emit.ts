// src/sdk-plugins/runtime-emit.ts
// String-emission helpers for runtime.ts. Split out so the runtime.ts emitter
// source stays under the 300-line house rule (mirrors auth.ts/auth-emit.ts and
// resource-tree.ts/resource-tree-pages.ts).
//
// Each function returns a block of EMITTED TypeScript. None run at SDK runtime.
// The emitted Client delegates auth header injection to AuthManager.applyAuth
// (auth.ts owns the AuthConfig union) and drives the retry loop described in the
// runtime contract: full-jitter backoff, optional Retry-After, method-class
// retryability, fresh Request per attempt, single auth-refresh outside the
// retry counter.

import type { RetriesConfig } from "./runtime.js";

export function emitHeader(): string {
  return [
    "// Auto-generated by @skillship/sdk-plugin-runtime. Do not edit by hand.",
    'import { throwForResponse, TimeoutError, UnauthorizedError, ConfigError } from "./errors.js";',
    'import { AuthManager, resolveAuthFromEnv, REQUIRED_ENV_VARS, type AuthConfig } from "./auth.js";',
    "",
    'export type { AuthConfig } from "./auth.js";',
  ].join("\n");
}

export function emitConstants(retries: RetriesConfig): string {
  const statusLiteral = `[${retries.retryableStatus.join(", ")}]`;
  return [
    "",
    `const MAX_RETRIES = ${retries.maxRetries};`,
    `const RETRYABLE_STATUS: readonly number[] = ${statusLiteral};`,
    "const BASE_DELAY_MS = 500;",
    "const MAX_DELAY_MS = 30000;",
    `const HONOR_RETRY_AFTER = ${retries.honorRetryAfter};`,
    'const IDEMPOTENT_METHODS: readonly string[] = ["GET", "HEAD", "PUT", "DELETE", "OPTIONS"];',
    "// Non-idempotent methods (POST/PATCH) retry ONLY these statuses, never network errors or timeouts.",
    "const NON_IDEMPOTENT_RETRYABLE: readonly number[] = [408, 429];",
  ].join("\n");
}

export function emitDefaultSleep(): string {
  return [
    "",
    "function defaultSleep(ms: number): Promise<void> {",
    "  return new Promise((resolve) => setTimeout(resolve, ms));",
    "}",
  ].join("\n");
}

