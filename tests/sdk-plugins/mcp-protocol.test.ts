// tests/sdk-plugins/mcp-protocol.test.ts
// TDD phase: source-pattern assertions + runtime-behavior tests.
// Runtime tests transpile the emitted module string with typescript's
// transpileModule() and evaluate it via a Function wrapper so the actual
// makeProtocolHandler() implementation is exercised — not just source patterns.
//
// runStdioServer's newline buffering and -32700 parse-error path are
// RUNTIME-TESTED via a testable seam: the emitted module exposes a
// processLine(line, handler) export that resolves to a response string or
// null. The full I/O wiring (stdin events) is source-asserted only, since
// driving real stdio in a unit test requires a child-process harness that would
// bloat the test and create race conditions. This choice keeps the emitted
// module clean: processLine is a pure async function with zero I/O coupling.

import { describe, expect, test } from "vitest";
import ts from "typescript";
import { generateMcpProtocolModule } from "../../src/sdk-plugins/mcp-protocol.js";

// ─── Runtime evaluation harness ──────────────────────────────────────────────

interface JsonRpcRequest {
  readonly jsonrpc: "2.0";
  readonly id?: number | string | null;
  readonly method: string;
  readonly params?: Record<string, unknown>;
}

interface JsonRpcResponse {
  readonly jsonrpc: "2.0";
  readonly id: number | string | null;
  readonly result?: unknown;
  readonly error?: { readonly code: number; readonly message: string };
}

interface ToolDef {
  name: string;
  description: string;
  inputSchema: Record<string, unknown>;
}

interface ToolResult {
  content: [{ type: "text"; text: string }];
  isError?: boolean;
}

interface EmittedExports {
  PROTOCOL_VERSION: string;
  JsonRpcRequest: unknown; // type-only, not runtime
  JsonRpcResponse: unknown; // type-only, not runtime
  makeProtocolHandler: (opts: {
    serverName: string;
    serverVersion: string;
    tools: readonly ToolDef[];
    callTool: (name: string, args: Record<string, unknown>) => Promise<ToolResult>;
  }) => (msg: JsonRpcRequest) => Promise<JsonRpcResponse | null>;
  runStdioServer: (handler: (msg: JsonRpcRequest) => Promise<JsonRpcResponse | null>) => void;
  processLine: (
    line: string,
    handler: (msg: JsonRpcRequest) => Promise<JsonRpcResponse | null>,
  ) => Promise<string | null>;
}

/** Transpile the emitted TS source to CJS and evaluate it. */
function loadEmittedModule(): EmittedExports {
  const src = generateMcpProtocolModule();
  const result = ts.transpileModule(src, {
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.CommonJS,
    },
  });
  const cjsWrapper = new Function("exports", "require", result.outputText);
  const exports: Record<string, unknown> = {};
  cjsWrapper(exports, () => {
    throw new Error("No imports expected in emitted protocol module");
  });
  return exports as EmittedExports;
}

/** Build a handler with two stub tools. */
function buildTestHandler(mod: EmittedExports): (msg: JsonRpcRequest) => Promise<JsonRpcResponse | null> {
  const tools: ToolDef[] = [
    {
      name: "echo",
      description: "Echoes input",
      inputSchema: { type: "object", properties: { text: { type: "string" } } },
    },
    {
      name: "add",
      description: "Adds two numbers",
      inputSchema: { type: "object", properties: { a: { type: "number" }, b: { type: "number" } } },
    },
  ];
  const callTool = async (name: string, args: Record<string, unknown>): Promise<ToolResult> => {
    if (name === "echo") {
      return { content: [{ type: "text", text: String(args["text"] ?? "") }] };
    }
    if (name === "add") {
      const result = (args["a"] as number) + (args["b"] as number);
      return { content: [{ type: "text", text: String(result) }] };
    }
    throw new Error("unexpected tool");
  };
  return mod.makeProtocolHandler({
    serverName: "test-server",
    serverVersion: "1.0.0",
    tools,
    callTool,
  });
}

/** Fire a single JSON-RPC message and return the parsed response. */
async function call(
  handler: (msg: JsonRpcRequest) => Promise<JsonRpcResponse | null>,
  req: JsonRpcRequest,
): Promise<JsonRpcResponse | null> {
  return handler(req);
}

